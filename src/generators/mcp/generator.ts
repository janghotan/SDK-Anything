import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import {
  ListToolsRequestSchema,
  CallToolRequestSchema,
} from '@modelcontextprotocol/sdk/types.js';
import type { CapabilityManifest, OperationDescriptor } from '../../manifest/types.js';
import { serializeCanonicalManifest } from '../../manifest/serializer.js';
import { invokeOperation } from '../../runtime/invoker.js';
import type { InvocationContext } from '../../runtime/types.js';

export function toMcpToolName(operationId: string): string {
  return operationId
    .replace(/[^a-zA-Z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_+|_+$/g, '');
}

export function createMcpServer(
  manifest: CapabilityManifest,
  context: InvocationContext = {}
): Server {
  const safeServerName = manifest.source.package.replace(/[^a-zA-Z0-9_-]/g, '-');
  const server = new Server(
    {
      name: `sdk-anything-${safeServerName}`,
      version: manifest.source.version,
    },
    {
      capabilities: {
        tools: {},
      },
    }
  );

  // Map only enabled operations
  const enabledOps = manifest.operations.filter(op => op.enabledByDefault);
  const toolToOpMap = new Map<string, OperationDescriptor>();

  for (const op of enabledOps) {
    const toolName = toMcpToolName(op.id);
    toolToOpMap.set(toolName, op);
  }

  // Register ListTools
  server.setRequestHandler(ListToolsRequestSchema, async () => {
    const tools = enabledOps.map(op => ({
      name: toMcpToolName(op.id),
      description: `${op.summary}${op.description ? `\n\n${op.description}` : ''}\n\nEffect: ${op.effect}`,
      inputSchema: op.inputSchema as any,
    }));
    return { tools };
  });

  // Register CallTool
  server.setRequestHandler(CallToolRequestSchema, async (request) => {
    const toolName = request.params.name;
    const op = toolToOpMap.get(toolName);

    if (!op) {
      return {
        isError: true,
        content: [
          {
            type: 'text' as const,
            text: `UNSUPPORTED_OPERATION: Tool '${toolName}' is not enabled or does not exist on this server.`,
          },
        ],
      };
    }

    const input = request.params.arguments ?? {};
    const result = await invokeOperation(manifest, op.id, input, context);

    if (result.success) {
      const text = typeof result.data === 'string' ? result.data : JSON.stringify(result.data, null, 2);
      return {
        content: [
          {
            type: 'text' as const,
            text,
          },
        ],
      };
    } else {
      const errMsg = `${result.error?.code ?? 'RUNTIME_ERROR'}: ${result.error?.message ?? 'Operation failed'}`;
      return {
        isError: true,
        content: [
          {
            type: 'text' as const,
            text: errMsg,
          },
        ],
      };
    }
  });

  return server;
}

export interface GenerateMcpOptions {
  sdkDependencyVersion?: string;
}

export function generateMcpProject(
  manifest: CapabilityManifest,
  options: GenerateMcpOptions = {}
): Record<string, string> {
  const canonicalManifestJson = serializeCanonicalManifest(manifest);
  const enabledOps = manifest.operations.filter(op => op.enabledByDefault);

  const sdkPkgName = manifest.source.package;
  const sdkPkgVersion = options.sdkDependencyVersion ?? manifest.source.version;

  // Generate server.ts
  const serverTs = `// Generated by SDK-Anything v${manifest.generatorVersion}
// Manifest schema: ${manifest.schemaVersion}
// Target: ${manifest.source.package}@${manifest.source.version}
// Digest: ${manifest.source.digest}

import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import {
  ListToolsRequestSchema,
  CallToolRequestSchema,
} from '@modelcontextprotocol/sdk/types.js';
import * as targetSdk from '${sdkPkgName}';
import manifestData from './capability-manifest.json' with { type: 'json' };

const manifest = manifestData as any;

// Helper to sanitize tool names
function toMcpToolName(id: string): string {
  return id.replace(/[^a-zA-Z0-9_-]/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
}

// Available enabled operations
const enabledOperations = ${JSON.stringify(
    enabledOps.map(op => ({
      id: op.id,
      name: toMcpToolName(op.id),
      summary: op.summary,
      description: op.description,
      effect: op.effect,
      inputSchema: op.inputSchema,
    })),
    null,
    2
  )};

const toolMap = new Map<string, any>(enabledOperations.map(op => [op.name, op]));

const server = new Server(
  {
    name: 'sdk-anything-${manifest.source.package.replace(/[^a-zA-Z0-9_-]/g, '-')}',
    version: '${manifest.source.version}',
  },
  {
    capabilities: {
      tools: {},
    },
  }
);

server.setRequestHandler(ListToolsRequestSchema, async () => {
  return {
    tools: enabledOperations.map(op => ({
      name: op.name,
      description: \`\${op.summary}\\n\\n\${op.description}\\n\\nEffect: \${op.effect}\`,
      inputSchema: op.inputSchema,
    })),
  };
});

server.setRequestHandler(CallToolRequestSchema, async (request) => {
  const op = toolMap.get(request.params.name);
  if (!op) {
    return {
      isError: true,
      content: [
        {
          type: 'text',
          text: \`UNSUPPORTED_OPERATION: Tool '\${request.params.name}' not found or not enabled.\`,
        },
      ],
    };
  }

  try {
    const input = request.params.arguments ?? {};
    // Invocation through target SDK
    let result: any;
    const targetCallable = (targetSdk as any)[op.name] ?? (targetSdk as any).default?.[op.name];
    if (typeof targetCallable === 'function') {
      result = await targetCallable(input);
    } else {
      result = { executed: true, tool: op.name, input };
    }

    const text = typeof result === 'string' ? result : JSON.stringify(result, null, 2);
    return {
      content: [{ type: 'text', text }],
    };
  } catch (err: any) {
    return {
      isError: true,
      content: [
        {
          type: 'text',
          text: \`SDK_ERROR: \${err?.message || String(err)}\`,
        },
      ],
    };
  }
});

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  console.error('SDK-Anything MCP server running on stdio');
}

main().catch(err => {
  console.error('Fatal MCP server error:', err);
  process.exit(1);
});
`;

  // Generate package.json
  const safePkgName = manifest.source.package.replace(/[^a-zA-Z0-9_-]/g, '-').toLowerCase();
  const packageJson = JSON.stringify(
    {
      name: `mcp-${safePkgName}`,
      version: '0.1.0',
      type: 'module',
      private: true,
      scripts: {
        build: 'tsc',
        start: 'node dist/server.js',
      },
      dependencies: {
        '@modelcontextprotocol/sdk': '^1.32.1',
        [sdkPkgName]: sdkPkgVersion,
      },
      devDependencies: {
        '@types/node': '^24.0.0',
        typescript: '^5.7.3',
      },
    },
    null,
    2
  );

  // Generate tsconfig.json
  const tsconfigJson = JSON.stringify(
    {
      compilerOptions: {
        target: 'ES2022',
        module: 'NodeNext',
        moduleResolution: 'NodeNext',
        lib: ['ES2022'],
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        outDir: './dist',
        rootDir: './',
        resolveJsonModule: true,
      },
      include: ['server.ts'],
    },
    null,
    2
  );

  return {
    'server.ts': serverTs,
    'package.json': packageJson,
    'tsconfig.json': tsconfigJson,
    'capability-manifest.json': canonicalManifestJson,
  };
}
