import { Server } from "@modelcontextprotocol/sdk/server/index.js";
import {
  ListToolsRequestSchema,
  CallToolRequestSchema,
} from "@modelcontextprotocol/sdk/types.js";
import type {
  CapabilityManifest,
  OperationDescriptor,
} from "../../manifest/types.js";
import { serializeCanonicalManifest } from "../../manifest/serializer.js";
import { invokeOperation } from "../../runtime/invoker.js";
import type { InvocationContext } from "../../runtime/types.js";
import { getStandaloneRuntimeSource } from "../runtime-template.js";
import { buildMcpToolNames } from "../naming.js";

export { toMcpToolName } from "../naming.js";

export function createMcpServer(
  manifest: CapabilityManifest,
  context: InvocationContext = {},
): Server {
  const safeServerName = manifest.source.package.replace(
    /[^a-zA-Z0-9_-]/g,
    "-",
  );
  const server = new Server(
    {
      name: `sdk-anything-${safeServerName}`,
      version: manifest.source.version,
    },
    {
      capabilities: {
        tools: {},
      },
      instructions: `This MCP server provides atomic tools generated from ${manifest.source.package}. Read and pure tools are safe for automated execution. Write, destructive, and unknown tools are discoverable but fail closed unless the server is started with explicit policy environment variables (SDK_ANYTHING_ALLOWED_EFFECTS, SDK_ANYTHING_ALLOWED_OPERATIONS, SDK_ANYTHING_ALLOW_DESTRUCTIVE).`,
    },
  );

  // Register every discovered operation. Disabled operations remain
  // discoverable but fail closed unless explicit policy is supplied.
  const toolToOpMap = new Map<string, OperationDescriptor>();
  const toolNames = buildMcpToolNames(manifest.operations);

  for (const op of manifest.operations) {
    toolToOpMap.set(toolNames.get(op.id)!, op);
  }

  // Register ListTools
  server.setRequestHandler(ListToolsRequestSchema, async () => {
    const tools = Array.from(toolToOpMap.entries()).map(([toolName, op]) => ({
      name: toolName,
      description: `${op.summary}${op.description ? `\n\n${op.description}` : ""}\n\nEffect: ${op.effect}${op.enabledByDefault ? "" : " (disabled by default; requires explicit policy)"}`,
      inputSchema: op.inputSchema as any,
    }));
    return { tools };
  });

  // Register CallTool
  server.setRequestHandler(CallToolRequestSchema, async (request: any) => {
    const toolName = request.params.name;
    const op = toolToOpMap.get(toolName);

    if (!op) {
      return {
        isError: true,
        content: [
          {
            type: "text" as const,
            text: `UNSUPPORTED_OPERATION: Tool '${toolName}' is not enabled or does not exist on this server.`,
          },
        ],
      };
    }

    const input = request.params.arguments ?? {};
    const result = await invokeOperation(manifest, op.id, input, context);

    if (result.success) {
      const text =
        typeof result.data === "string"
          ? result.data
          : JSON.stringify(result.data, null, 2);
      return {
        content: [
          {
            type: "text" as const,
            text,
          },
        ],
      };
    } else {
      const errMsg = `${result.error?.code ?? "RUNTIME_ERROR"}: ${result.error?.message ?? "Operation failed"}`;
      return {
        isError: true,
        content: [
          {
            type: "text" as const,
            text: errMsg,
          },
        ],
      };
    }
  });

  return server;
}

export interface GenerateMcpOptions {
  sdkDependencyVersion?: string;
  sdkDependencySpec?: string;
}

export function generateMcpProject(
  manifest: CapabilityManifest,
  options: GenerateMcpOptions = {},
): Record<string, string> {
  const canonicalManifestJson = serializeCanonicalManifest(manifest);
  const toolNames = buildMcpToolNames(manifest.operations);

  const sdkPkgName = manifest.source.package;
  const sdkPkgVersion =
    options.sdkDependencySpec ??
    options.sdkDependencyVersion ??
    manifest.source.version;

  const mappedMcpOps = manifest.operations.map((op) => ({
    id: op.id,
    name: toolNames.get(op.id)!,
    summary: op.summary,
    description: op.description,
    effect: op.effect,
    enabledByDefault: op.enabledByDefault,
    inputSchema: op.inputSchema,
  }));

  // Generate server.ts
  const serverTs = `// Generated by SDK-Anything v${manifest.generatorVersion}
// Manifest schema: ${manifest.schemaVersion}
// Target: ${manifest.source.package}@${manifest.source.version}
// Digest: ${manifest.source.digest}

import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import {
  ListToolsRequestSchema,
  CallToolRequestSchema,
} from '@modelcontextprotocol/sdk/types.js';
import * as targetSdk from '${sdkPkgName}';
import { invokeOperation, loadManifest } from './runtime.js';

const manifest = loadManifest();

const commandOperations = ${JSON.stringify(mappedMcpOps, null, 2)};

const toolMap = new Map<string, any>(commandOperations.map(op => [op.name, op]));

function readListEnv(name: string): string[] | undefined {
  const raw = process.env[name];
  if (!raw) return undefined;
  const values = raw.split(',').map(value => value.trim()).filter(Boolean);
  return values.length > 0 ? values : undefined;
}

const policyContext = {
  sdkModule: targetSdk,
  env: process.env,
  interactive: false as const,
  allowedEffects: readListEnv('SDK_ANYTHING_ALLOWED_EFFECTS') as any,
  allowedOperationIds: readListEnv('SDK_ANYTHING_ALLOWED_OPERATIONS'),
  allowDestructive: process.env.SDK_ANYTHING_ALLOW_DESTRUCTIVE === 'true',
};

const server = new Server(
  {
    name: 'sdk-anything-${manifest.source.package.replace(/[^a-zA-Z0-9_-]/g, "-")}',
    version: '${manifest.source.version}',
  },
  {
    capabilities: {
      tools: {},
    },
    instructions: 'This MCP server provides atomic tools generated from ${manifest.source.package}. Read and pure tools are safe for automated execution. Write, destructive, and unknown tools are discoverable but fail closed unless the server is started with explicit policy environment variables (SDK_ANYTHING_ALLOWED_EFFECTS, SDK_ANYTHING_ALLOWED_OPERATIONS, SDK_ANYTHING_ALLOW_DESTRUCTIVE).',
  }
);

server.setRequestHandler(ListToolsRequestSchema, async () => {
  return {
    tools: commandOperations.map(op => ({
      name: op.name,
      description: \`\${op.summary}\\n\\n\${op.description}\\n\\nEffect: \${op.effect}\${op.enabledByDefault ? '' : ' (disabled by default; requires explicit policy)'}\`,
      inputSchema: op.inputSchema,
    })),
  };
});

server.setRequestHandler(CallToolRequestSchema, async (request: any) => {
  const op = toolMap.get(request.params.name);
  if (!op) {
    return {
      isError: true,
      content: [
        {
          type: 'text',
          text: \`UNSUPPORTED_OPERATION: Tool '\${request.params.name}' not found.\`,
        },
      ],
    };
  }

  const input = request.params.arguments ?? {};
  const result = await invokeOperation(manifest, op.id, input, policyContext);

  if (result.success) {
    const text = typeof result.data === 'string' ? result.data : JSON.stringify(result.data, null, 2);
    return {
      content: [{ type: 'text', text }],
    };
  } else {
    return {
      isError: true,
      content: [
        {
          type: 'text',
          text: \`\${result.error?.code ?? 'SDK_ERROR'}: \${result.error?.message ?? 'Operation failed'}\`,
        },
      ],
    };
  }
});

async function main() {
  const transport = new StdioServerTransport();
  await server.connect(transport);
  console.error('SDK-Anything MCP server running on stdio');
}

main().catch((err: unknown) => {
  console.error('Fatal MCP server error:', err);
  process.exit(1);
});
`;

  // Generate package.json
  const safePkgName = manifest.source.package
    .replace(/[^a-zA-Z0-9_-]/g, "-")
    .toLowerCase();
  const packageJson = JSON.stringify(
    {
      name: `mcp-${safePkgName}`,
      version: "0.1.0",
      type: "module",
      private: true,
      scripts: {
        build:
          "tsc && node -e \"require('node:fs').copyFileSync('capability-manifest.json','dist/capability-manifest.json')\"",
        start: "node dist/server.js",
        test: "tsc --noEmit",
      },
      dependencies: {
        "@modelcontextprotocol/sdk": "^1.32.1",
        ajv: "^8.20.0",
        "ajv-formats": "^3.0.1",
        [sdkPkgName]: sdkPkgVersion,
      },
      devDependencies: {
        "@types/node": "^24.0.0",
        typescript: "^5.7.3",
      },
    },
    null,
    2,
  );

  // Generate tsconfig.json
  const tsconfigJson = JSON.stringify(
    {
      compilerOptions: {
        target: "ES2022",
        module: "NodeNext",
        moduleResolution: "NodeNext",
        lib: ["ES2022"],
        types: ["node"],
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        outDir: "./dist",
        rootDir: "./",
        resolveJsonModule: true,
      },
      include: ["server.ts", "runtime.ts"],
    },
    null,
    2,
  );

  const envPlaceholders: Record<string, string> = {};
  if (manifest.client?.options) {
    for (const [_, opt] of Object.entries(manifest.client.options)) {
      if (opt.source && opt.source.startsWith("env:")) {
        const envName = opt.source.slice(4);
        envPlaceholders[envName] = "<YOUR_SECRET_OR_CONFIG_VALUE>";
      }
    }
  }

  const claudeDesktopConfigJson = JSON.stringify(
    {
      mcpServers: {
        [safePkgName]: {
          command: "node",
          args: ["./dist/server.js"],
          env:
            Object.keys(envPlaceholders).length > 0
              ? envPlaceholders
              : undefined,
        },
      },
    },
    null,
    2,
  );

  return {
    "server.ts": serverTs,
    "runtime.ts": getStandaloneRuntimeSource(),
    "package.json": packageJson,
    "tsconfig.json": tsconfigJson,
    "capability-manifest.json": canonicalManifestJson,
    "claude_desktop_config.json": claudeDesktopConfigJson,
  };
}
