export function getStandaloneRuntimeSource(): string {
  return `// Generated by SDK-Anything - Shared Runtime Layer

export type OperationEffect = 'pure' | 'read' | 'write' | 'destructive' | 'unknown';

export interface InvocationContext {
  env?: Record<string, string | undefined>;
  allowedEffects?: OperationEffect[];
  allowedOperationIds?: string[];
  timeoutMs?: number;
  maxItems?: number;
  maxBytes?: number;
  interactive?: boolean;
  allowDestructive?: boolean;
  confirmDestructive?: (opId: string) => Promise<boolean>;
  sdkInstance?: unknown;
  sdkModule?: any;
  signal?: AbortSignal;
}

export interface InvocationResult {
  success: boolean;
  operationId: string;
  data?: unknown;
  error?: {
    code: string;
    message: string;
    suggestedAction?: string;
  };
  truncated?: boolean;
  executionTimeMs: number;
}

export function redactSecrets(text: string, knownSecrets: string[] = []): string {
  let result = text;
  for (const secret of knownSecrets) {
    if (secret && secret.length >= 4) {
      result = result.split(secret).join('[REDACTED]');
    }
  }
  result = result.replace(/bearer\\s+[A-Za-z0-9._~+/-]+=*/gi, 'Bearer [REDACTED]');
  result = result.replace(/(api[_-]?key|token|secret|password)\\s*[:=]\\s*['"]?[A-Za-z0-9._~+/-]{8,}['"]?/gi, '$1=[REDACTED]');
  result = result.replace(/:\\/\\/[^:\\s]+:[^@\\s]+@/g, '://[REDACTED]:[REDACTED]@');
  result = result.replace(/([?&](?:api[_-]?key|token|secret|password|access_token)=)[^&\\s]+/gi, '$1[REDACTED]');
  return result;
}

export function normalizeError(err: unknown, knownSecrets: string[] = []) {
  if (!err) return { code: 'RUNTIME_ERROR', message: 'Unknown error occurred' };
  const rawMessage = err instanceof Error ? err.message : String(err);
  const message = redactSecrets(rawMessage, knownSecrets);
  let code = 'RUNTIME_ERROR';

  if (/policy denied|permission denied|disabled by default|unauthorized effect/i.test(message)) {
    code = 'POLICY_DENIED';
  } else if (/unauthorized|authentication required|invalid token|api key|401|forbidden|403|\\bauth\\b/i.test(message)) {
    code = 'AUTH_REQUIRED';
  } else if (/not found|404/i.test(message)) {
    code = 'NOT_FOUND';
  } else if (/rate limit|too many requests|429/i.test(message)) {
    code = 'RATE_LIMITED';
  } else if (/timed? out|timeout/i.test(message)) {
    code = 'TIMEOUT';
  } else if (/invalid input|validation failed|missing required property/i.test(message)) {
    code = 'INVALID_INPUT';
  } else if (/sdk error|network error|econnrefused|fetch failed/i.test(message)) {
    code = 'SDK_ERROR';
  }

  return { code, message };
}

export function resolveClient(clientDesc: any, context: InvocationContext) {
  const knownSecrets: string[] = [];
  if (!clientDesc || clientDesc.construction === 'none') {
    return { clientInstance: context.sdkInstance ?? context.sdkModule, knownSecrets };
  }
  if (context.sdkInstance) {
    return { clientInstance: context.sdkInstance, knownSecrets };
  }

  const env = context.env ?? process.env;
  const resolvedOptions: Record<string, any> = {};

  if (clientDesc.options) {
    for (const [key, opt] of Object.entries<any>(clientDesc.options)) {
      if (opt.source && opt.source.startsWith('env:')) {
        const envVarName = opt.source.slice(4);
        const val = env[envVarName];
        if (!val && opt.required) {
          throw new Error(\`Authentication required: environment variable '\${envVarName}' for client option '\${key}' is not set\`);
        }
        if (val) {
          resolvedOptions[key] = val;
          if (opt.type === 'secret') knownSecrets.push(val);
        }
      } else if (opt.required && resolvedOptions[key] === undefined) {
        throw new Error(\`Required client configuration option '\${key}' is missing\`);
      }
    }
  }

  const sdkModule = context.sdkModule;
  if (!sdkModule) throw new Error('Target SDK module not provided in invocation context');

  const exportTarget = sdkModule[clientDesc.export] ?? (sdkModule.default && sdkModule.default[clientDesc.export]);
  if (!exportTarget) throw new Error(\`Export '\${clientDesc.export}' not found on SDK module\`);

  let clientInstance: any;
  if (clientDesc.construction === 'class') {
    clientInstance = new exportTarget(resolvedOptions);
  } else if (clientDesc.construction === 'factory') {
    clientInstance = exportTarget(resolvedOptions);
  } else {
    clientInstance = exportTarget;
  }

  return { clientInstance, knownSecrets };
}

export async function enforceOperationPolicy(op: any, context: InvocationContext): Promise<void> {
  const allowedEffects = [
    ...(context.allowedEffects ?? ['pure', 'read']),
  ];
  if (context.allowDestructive || context.allowedOperationIds?.includes(op.id)) {
    if (!allowedEffects.includes('destructive')) {
      allowedEffects.push('destructive');
    }
  }
  if (context.allowedOperationIds && !context.allowedOperationIds.includes(op.id)) {
    throw new Error(\`Policy denied: operation '\${op.id}' is not in the explicit allowedOperationIds list\`);
  }
  if (!allowedEffects.includes(op.effect)) {
    throw new Error(\`Policy denied: operation '\${op.id}' has effect '\${op.effect}', which is disabled by default.\`);
  }
  const isExplicitlyAuthorized =
    (context.allowedEffects && context.allowedEffects.includes(op.effect)) ||
    (op.effect === 'destructive' && context.allowDestructive) ||
    context.allowedOperationIds?.includes(op.id);

  if (!op.enabledByDefault && !isExplicitlyAuthorized) {
    throw new Error(\`Policy denied: operation '\${op.id}' is disabled by default in manifest.\`);
  }
  if (op.effect === 'destructive') {
    if (context.interactive) {
      if (context.confirmDestructive) {
        const confirmed = await context.confirmDestructive(op.id);
        if (!confirmed) throw new Error(\`Policy denied: destructive operation '\${op.id}' was rejected by user confirmation\`);
      } else {
        throw new Error(\`Policy denied: destructive operation '\${op.id}' requires interactive confirmation\`);
      }
    } else if (context.interactive === false) {
      if (!context.allowDestructive && !context.allowedOperationIds?.includes(op.id)) {
        throw new Error(\`Policy denied: destructive operation '\${op.id}' cannot be executed in non-interactive environment without explicit authorization (allowDestructive: true or allowedOperationIds)\`);
      }
    }
  }
}

export function boundResult(data: any, paginationDesc?: any, contextCaps?: { maxItems?: number; maxBytes?: number }) {
  if (data === null || data === undefined) return { data, truncated: false };
  const maxItems = contextCaps?.maxItems ?? paginationDesc?.maxItems ?? 100;
  const maxBytes = contextCaps?.maxBytes ?? paginationDesc?.maxBytes ?? 1048576;
  let truncated = false;
  let result = data;

  if (Array.isArray(data)) {
    if (data.length > maxItems) {
      result = data.slice(0, maxItems);
      truncated = true;
    }
  } else if (typeof data === 'object') {
    const itemsField = paginationDesc?.responseItemsField ?? 'items';
    if (Array.isArray(data[itemsField]) && data[itemsField].length > maxItems) {
      result = { ...data, [itemsField]: data[itemsField].slice(0, maxItems) };
      truncated = true;
    }
  }

  try {
    const jsonStr = JSON.stringify(result);
    if (Buffer.byteLength(jsonStr, 'utf8') > maxBytes) {
      truncated = true;
    }
  } catch {}

  return { data: result, truncated };
}

export function validatePaginationCursor(cursor: string | undefined, seenCursors: Set<string>): void {
  if (!cursor) return;
  if (seenCursors.has(cursor)) {
    throw new Error(\`Infinite pagination loop detected: cursor '\${cursor}' was already seen\`);
  }
  seenCursors.add(cursor);
}

export async function invokeOperation(
  manifest: any,
  operationId: string,
  input: unknown,
  context: InvocationContext = {}
): Promise<InvocationResult> {
  const startTime = Date.now();
  const knownSecrets: string[] = [];

  try {
    const op = manifest.operations?.find((o: any) => o.id === operationId);
    if (!op) {
      return {
        success: false,
        operationId,
        error: { code: 'UNSUPPORTED_OPERATION', message: \`Operation '\${operationId}' not found in manifest\` },
        executionTimeMs: Date.now() - startTime,
      };
    }

    await enforceOperationPolicy(op, context);

    let targetCallable: any;
    let thisArg: any = null;

    if (op.invoke?.kind === 'instance-method') {
      const clientRes = resolveClient(manifest.client, context);
      knownSecrets.push(...clientRes.knownSecrets);
      const clientInstance = clientRes.clientInstance;
      const methodName = op.invoke.method!;
      if (!clientInstance || typeof clientInstance[methodName] !== 'function') {
        throw new Error(\`Method '\${methodName}' not found on client instance\`);
      }
      targetCallable = clientInstance[methodName];
      thisArg = clientInstance;
    } else {
      const sdkModule = context.sdkModule;
      if (!sdkModule) throw new Error('Target SDK module not provided');
      const fnName = op.invoke?.functionName!;
      targetCallable = sdkModule[fnName] ?? (sdkModule.default && sdkModule.default[fnName]);
      if (typeof targetCallable !== 'function') {
        throw new Error(\`Function '\${fnName}' not found on SDK module\`);
      }
    }

    const timeoutMs = context.timeoutMs ?? 30000;
    const executionPromise = (async () => {
      if (typeof input === 'object' && input !== null) {
        const propKeys = Object.keys(op.inputSchema?.properties || {});
        if (propKeys.length === 1 && propKeys[0] in (input as any)) {
          return targetCallable.call(thisArg, (input as any)[propKeys[0]]);
        }
        if (targetCallable.length > 1 && propKeys.length > 1) {
          const positional = propKeys.map(k => (input as any)[k]);
          return targetCallable.apply(thisArg, positional);
        }
        return targetCallable.call(thisArg, input);
      }
      return targetCallable.call(thisArg);
    })();

    if (context.signal?.aborted) {
      throw new Error(\`Operation '\${operationId}' was cancelled before execution\`);
    }

    let timer: any;
    const timeoutPromise = new Promise((_, reject) => {
      timer = setTimeout(() => reject(new Error(\`Operation '\${operationId}' timed out after \${timeoutMs}ms\`)), timeoutMs);
    });

    let abortListener: (() => void) | undefined;
    const abortPromise = new Promise((_, reject) => {
      if (context.signal) {
        abortListener = () => {
          reject(new Error(\`Operation '\${operationId}' was cancelled by AbortSignal\`));
        };
        context.signal.addEventListener('abort', abortListener, { once: true });
      }
    });

    const rawResult = await Promise.race([executionPromise, timeoutPromise, abortPromise]).finally(() => {
      clearTimeout(timer);
      if (context.signal && abortListener) {
        context.signal.removeEventListener('abort', abortListener);
      }
    });
    const bounded = boundResult(rawResult, op.result?.pagination, { maxItems: context.maxItems, maxBytes: context.maxBytes });

    return {
      success: true,
      operationId,
      data: bounded.data,
      truncated: bounded.truncated,
      executionTimeMs: Date.now() - startTime,
    };
  } catch (err: unknown) {
    const norm = normalizeError(err, knownSecrets);
    return {
      success: false,
      operationId,
      error: norm,
      executionTimeMs: Date.now() - startTime,
    };
  }
}
`;
}
