export interface GenerateArtifactsOptions {
  sdkDependencyVersion?: string;
  /** Explicit npm dependency specifier for the target SDK, e.g. file:./vendor/sdk. */
  sdkDependencySpec?: string;
  /** Copy a built SDK package directory into the generated project for standalone use. */
  vendorSdkPath?: string;
  force?: boolean;
  check?: boolean;
}

function copyDirectoryFiltered(src: string, dest: string): void {
  fs.mkdirSync(dest, { recursive: true });
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    if (entry.name === ".git" || entry.name === "node_modules") {
      continue;
    }
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirectoryFiltered(srcPath, destPath);
    } else if (entry.isFile()) {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

export function generateProjectReadme(
  manifest: CapabilityManifest,
  targets: string[] = ["mcp", "cli"],
): string {
  const pkg = manifest.source.package;
  const version = manifest.source.version;
  const digest = manifest.source.digest;
  const safeName = pkg.replace(/[^a-zA-Z0-9_-]/g, "-").toLowerCase();

  const lines: string[] = [];
  lines.push(`# Generated Agent Capabilities for ${pkg}`);
  lines.push("");
  lines.push(`- **Target Package:** \`${pkg}@${version}\``);
  lines.push(`- **Source Digest:** \`${digest}\``);
  lines.push(`- **Manifest Schema:** \`${manifest.schemaVersion}\``);
  lines.push(`- **Generated Targets:** ${targets.join(", ")}`);
  lines.push("");
  lines.push("## Overview");
  lines.push("");
  lines.push(
    `This project contains agent-native interfaces generated by [SDK-Anything](https://github.com/janghotan/SDK-Anything) from \`${pkg}\`.`,
  );
  lines.push(
    "It provides self-contained, independently usable MCP server tools and a CLI for developer and autonomous agent use.",
  );
  lines.push("");
  lines.push("## Directory Contents");
  lines.push("");
  lines.push(
    "- `capability-manifest.json`: Single source of truth defining all discovered operations, schemas, and effect tiers.",
  );
  lines.push("- `SKILL.md`: Guidance manual for AI consumer agents.");
  if (targets.includes("cli")) {
    lines.push("- `cli/`: Standalone command-line interface project.");
  }
  if (targets.includes("mcp")) {
    lines.push(
      "- `mcp/`: Standalone Model Context Protocol (MCP) server project.",
    );
  }
  lines.push("");
  lines.push("## Quickstart");
  lines.push("");

  if (targets.includes("cli")) {
    lines.push("### 1. Using the Generated CLI");
    lines.push("");
    lines.push("```bash");
    lines.push("cd cli");
    lines.push("npm install");
    lines.push("npm run build");
    lines.push(`node dist/cli.js --help`);
    lines.push(`node dist/cli.js list --json`);
    lines.push("```");
    lines.push("");
  }

  if (targets.includes("mcp")) {
    lines.push("### 2. Running the MCP Server");
    lines.push("");
    lines.push("```bash");
    lines.push("cd mcp");
    lines.push("npm install");
    lines.push("npm run build");
    lines.push("node dist/server.js");
    lines.push("```");
    lines.push("");
    lines.push(
      "To configure an MCP client (such as Claude Desktop or Cursor), add:",
    );
    lines.push("");
    lines.push("```json");
    lines.push("{");
    lines.push('  "mcpServers": {');
    lines.push(`    "${safeName}": {`);
    lines.push('      "command": "node",');
    lines.push('      "args": ["./mcp/dist/server.js"]');
    lines.push("    }");
    lines.push("  }");
    lines.push("}");
    lines.push("```");
    lines.push("");
  }

  lines.push("## Safety & Policy Defaults");
  lines.push("");
  lines.push(
    "- **Pure & Read:** Operations with pure functional calculations or read-only queries are enabled by default.",
  );
  lines.push(
    "- **Write & Destructive:** Operations with write or destructive effects are disabled by default.",
  );
  lines.push(
    "- **Fail-Closed:** In non-interactive environments, destructive operations fail closed unless `--allow-destructive` is explicitly authorized.",
  );
  lines.push("");

  return lines.join("\n");
}

export function generateArtifacts(
  manifest: CapabilityManifest,
  targets: string[] = ["mcp", "cli"],
  outputDir: string,
  options: GenerateArtifactsOptions = {},
): string[] {
  const resolvedOutDir = path.resolve(outputDir);

  for (const target of targets) {
    if (
      target.includes("..") ||
      target.includes("/") ||
      target.includes("\\")
    ) {
      throw new Error(
        `Path traversal detected: invalid generation target '${target}' escapes output directory '${resolvedOutDir}'`,
      );
    }
  }

  // Staging map of relativeFilePath -> fileContent
  const fileMap = new Map<string, string>();

  const safeSdkName = manifest.source.package
    .replace(/[^a-zA-Z0-9_-]/g, "-")
    .toLowerCase();

  let vendorRelDir: string | undefined;
  let sdkDependencySpec = options.sdkDependencySpec;
  if (options.vendorSdkPath) {
    const vendorSrc = path.resolve(options.vendorSdkPath);
    if (!fs.existsSync(vendorSrc) || !fs.statSync(vendorSrc).isDirectory()) {
      throw new Error(
        `Vendored SDK path does not exist or is not a directory: ${vendorSrc}`,
      );
    }
    const vendorPkgJsonPath = path.join(vendorSrc, "package.json");
    if (!fs.existsSync(vendorPkgJsonPath)) {
      throw new Error(
        `Vendored SDK directory is missing package.json: ${vendorSrc}`,
      );
    }
    let vendorPackageName: string | undefined;
    try {
      vendorPackageName = JSON.parse(
        fs.readFileSync(vendorPkgJsonPath, "utf8"),
      ).name;
    } catch (err: unknown) {
      throw new Error(
        `Could not read vendored SDK package.json: ${err instanceof Error ? err.message : String(err)}`,
      );
    }
    if (vendorPackageName !== manifest.source.package) {
      throw new Error(
        `Vendored SDK package name '${vendorPackageName ?? "<missing>"}' does not match manifest source package '${manifest.source.package}'`,
      );
    }
    vendorRelDir = path.join("vendor", safeSdkName);
    const vendorTarget = path.resolve(resolvedOutDir, vendorRelDir);
    if (
      !vendorTarget.startsWith(resolvedOutDir + path.sep) &&
      vendorTarget !== resolvedOutDir
    ) {
      throw new Error(
        `Path traversal detected: vendored SDK target '${vendorTarget}' escapes output directory '${resolvedOutDir}'`,
      );
    }
    sdkDependencySpec =
      sdkDependencySpec ??
      // Adapter package.json files live under `cli/` and `mcp/`, so the
      // project-root `vendor/` directory is one level up.
      `file:../${vendorRelDir.replace(/\\/g, "/")}`;
  }

  const generatorOptions = {
    ...options,
    sdkDependencySpec,
  };

  // 1. capability-manifest.json
  fileMap.set("capability-manifest.json", JSON.stringify(manifest, null, 2));

  // 2. SKILL.md
  fileMap.set("SKILL.md", generateConsumerSkill(manifest));

  // 3. README.md
  fileMap.set("README.md", generateProjectReadme(manifest, targets));

  // 4. MCP Adapter
  if (targets.includes("mcp")) {
    const mcpFiles = generateMcpProject(manifest, generatorOptions);
    for (const [relPath, content] of Object.entries(mcpFiles)) {
      fileMap.set(path.join("mcp", relPath), content);
    }
  }

  // 5. CLI Adapter
  if (targets.includes("cli")) {
    const cliFiles = generateCliProject(manifest, generatorOptions);
    for (const [relPath, content] of Object.entries(cliFiles)) {
      fileMap.set(path.join("cli", relPath), content);
    }
  }

  // Add artifact inventory to fileMap
  const inventory = createArtifactInventory(
    fileMap,
    manifest.source.digest,
    manifest.generatorVersion,
  );
  fileMap.set(
    ".sdk-anything-inventory.json",
    JSON.stringify(inventory, null, 2),
  );

  // Verify all paths stay within resolvedOutDir
  for (const relPath of fileMap.keys()) {
    const targetPath = path.resolve(resolvedOutDir, relPath);
    if (
      !targetPath.startsWith(resolvedOutDir + path.sep) &&
      targetPath !== resolvedOutDir
    ) {
      throw new Error(
        `Path traversal detected: generated path '${targetPath}' escapes output directory '${resolvedOutDir}'`,
      );
    }
  }

  // Drift check
  const drift = checkDrift(resolvedOutDir, fileMap);

  if (options.check) {
    if (vendorRelDir) {
      const vendorTarget = path.join(resolvedOutDir, vendorRelDir);
      if (!fs.existsSync(vendorTarget)) {
        throw new Error(
          `Drift detected in generated project at ${resolvedOutDir}:\n  Missing vendored SDK directory: ${vendorRelDir}`,
        );
      }
    }
    if (drift.hasDrift) {
      const details = [
        drift.addedFiles.length > 0
          ? `  Added: ${drift.addedFiles.join(", ")}`
          : "",
        drift.removedFiles.length > 0
          ? `  Removed: ${drift.removedFiles.join(", ")}`
          : "",
        drift.modifiedFiles.length > 0
          ? `  Modified: ${drift.modifiedFiles.join(", ")}`
          : "",
      ]
        .filter(Boolean)
        .join("\n");
      throw new Error(
        `Drift detected in generated project at ${resolvedOutDir}:\n${details}`,
      );
    }
    return Array.from(fileMap.keys()).map((rel) =>
      path.join(resolvedOutDir, rel),
    );
  }

  // Check for user-modified conflicts
  if (drift.userModifiedConflicts.length > 0 && !options.force) {
    throw new Error(
      `Conflict detected: The following files have been modified by user since last generation: ${drift.userModifiedConflicts.join(", ")}. Pass --force to overwrite user modifications, or merge changes manually.`,
    );
  }

  // Atomic write via staging directory
  const stageId = crypto.randomBytes(8).toString("hex");
  const stageDir = path.join(os.tmpdir(), `sdk-stage-${stageId}`);
  fs.mkdirSync(stageDir, { recursive: true });

  const writtenFiles: string[] = [];

  try {
    // Write all files to staging directory first
    for (const [relPath, content] of fileMap.entries()) {
      const stageFilePath = path.join(stageDir, relPath);
      fs.mkdirSync(path.dirname(stageFilePath), { recursive: true });
      fs.writeFileSync(stageFilePath, content, "utf8");
    }

    // Now copy from staging to output directory
    fs.mkdirSync(resolvedOutDir, { recursive: true });
    for (const [relPath, content] of fileMap.entries()) {
      const destFilePath = path.join(resolvedOutDir, relPath);
      fs.mkdirSync(path.dirname(destFilePath), { recursive: true });
      fs.writeFileSync(destFilePath, content, "utf8");
      writtenFiles.push(destFilePath);
    }

    // Copy the vendored SDK package alongside the generated adapters so the
    // project can be installed and built without access to the source checkout.
    if (options.vendorSdkPath && vendorRelDir) {
      const vendorDest = path.join(resolvedOutDir, vendorRelDir);
      copyDirectoryFiltered(path.resolve(options.vendorSdkPath), vendorDest);
    }
  } finally {
    try {
      fs.rmSync(stageDir, { recursive: true, force: true });
    } catch {
      // Ignore cleanup error
    }
  }

  return writtenFiles;
}
