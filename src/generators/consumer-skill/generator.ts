import type { CapabilityManifest } from '../../manifest/types.js';
import { toMcpToolName } from '../mcp/generator.js';
import { toCliCommandName } from '../cli/generator.js';

export function generateConsumerSkill(manifest: CapabilityManifest): string {
  const pkg = manifest.source.package;
  const version = manifest.source.version;
  const digest = manifest.source.digest;

  const enabledOps = manifest.operations.filter(op => op.enabledByDefault);
  const disabledOps = manifest.operations.filter(op => !op.enabledByDefault);

  const lines: string[] = [];

  lines.push(`# ${pkg} Capability Skill`);
  lines.push('');
  lines.push(`> Automatically generated by SDK-Anything v${manifest.generatorVersion}`);
  lines.push(`> Target Package: \`${pkg}@${version}\` | Source Digest: \`${digest}\``);
  lines.push('');
  lines.push('## Overview');
  lines.push('');
  lines.push(`This Skill teaches an AI agent how to discover, configure, and invoke tools generated from \`${pkg}\`.`);
  lines.push('All exposed tools are atomic operations. Multi-step workflows should be orchestrated by the consuming agent calling atomic tools in sequence.');
  lines.push('');

  // Client configuration & Credentials
  if (manifest.client && Object.keys(manifest.client.options).length > 0) {
    lines.push('## Required Configuration and Credentials');
    lines.push('');
    lines.push('Before calling client-based operations, ensure the following environment variables are set:');
    lines.push('');
    lines.push('| Option | Type | Required | Environment Variable / Source | Description |');
    lines.push('|---|---|---|---|---|');
    for (const [key, opt] of Object.entries(manifest.client.options)) {
      const src = opt.source ? `\`${opt.source}\`` : 'direct option';
      lines.push(`| \`${key}\` | \`${opt.type}\` | ${opt.required ? '**Yes**' : 'No'} | ${src} | ${opt.description ?? '—'} |`);
    }
    lines.push('');
  }

  // Available Tools
  lines.push('## Available Atomic Tools');
  lines.push('');
  lines.push('These tools are enabled by default and safe for agent use:');
  lines.push('');
  lines.push('| MCP Tool Name | CLI Command | Effect | Description |');
  lines.push('|---|---|---|---|');
  for (const op of enabledOps) {
    const mcpName = toMcpToolName(op.id);
    const cliName = toCliCommandName(op.id);
    lines.push(`| \`${mcpName}\` | \`${cliName}\` | \`${op.effect}\` | ${op.summary} |`);
  }
  lines.push('');

  // Composition Guidance
  lines.push('## Atomic Operation Composition');
  lines.push('');
  lines.push('In SDK-Anything v0.1, all generated operations are atomic. To achieve composite goals:');
  lines.push('1. **Discover:** Check the tools table above for the relevant atomic capabilities.');
  lines.push('2. **Inspect:** Call the first tool with the necessary parameters and inspect the structured JSON response.');
  lines.push('3. **Transform:** Process or validate the response in your reasoning context.');
  lines.push('4. **Chain:** Pass the required output fields into subsequent atomic tools.');
  lines.push('5. **Handle Errors:** If an operation returns an error code (such as `NOT_FOUND` or `RATE_LIMITED`), apply appropriate fallback or retry strategies.');
  lines.push('');

  // Disabled and Destructive Operations
  if (disabledOps.length > 0) {
    lines.push('## Disabled Operations');
    lines.push('');
    lines.push('The following operations were discovered but are disabled by default according to SDK-Anything security policy (write, destructive, or unknown effect):');
    lines.push('');
    lines.push('| Operation ID | Effect | Default Status | How to Enable |');
    lines.push('|---|---|---|---|');
    for (const op of disabledOps) {
      lines.push(`| \`${op.id}\` | \`${op.effect}\` | Disabled | Enable in policy configuration or \`sdk-anything.overrides.json\` |`);
    }
    lines.push('');
  }

  // Unresolved
  if (manifest.unresolved.length > 0) {
    lines.push('## Unresolved Capabilities');
    lines.push('');
    lines.push('These symbols could not be fully resolved statically and require human review:');
    lines.push('');
    for (const u of manifest.unresolved) {
      lines.push(`- **${u.id}**: ${u.reason} *(Suggested action: ${u.suggestedAction})*`);
    }
    lines.push('');
  }

  lines.push('## Security & Runtime Policy');
  lines.push('');
  lines.push('- **Pure & Read:** Available by default.');
  lines.push('- **Write & Destructive:** Blocked at runtime unless explicitly enabled.');
  lines.push('- **Credentials:** Managed strictly via environment variable references; never pass secret values directly in tool arguments.');
  lines.push('- **Pagination:** Results are strictly bounded by count and response byte limits to prevent memory exhaustion.');
  lines.push('');

  return lines.join('\n');
}
